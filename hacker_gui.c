// Uses stable firmware-validated short acoustic beep macro indicators
static const NotificationSequence jingle_sequence = {
    &message_note_c5,   // Step 1: Play C5
    &message_delay_100, // Step 2: Sleep duration pause
    &message_note_e5,   // Step 3: Play E5
    &message_delay_100, 
    &message_note_g5,   // Step 4: Play G5
    &message_delay_250, 
    &message_sound_off, // Mute sound off pipeline on exit
    NULL
};

typedef struct {
    uint8_t progress;
    bool sound_played; 
} AppState;

static void draw_callback(Canvas* canvas, void* ctx) {
    AppState* state = (AppState*)ctx;
    canvas_clear(canvas);
    
    uint8_t x_offset = (128 - IMG_WIDTH) / 2;
    canvas_set_color(canvas, ColorBlack);
    canvas_draw_xbm(canvas, x_offset, 0, IMG_WIDTH, IMG_HEIGHT, hacker_bitmap);
    
    canvas_set_color(canvas, ColorBlack);
    uint8_t bar_width = (state->progress * 128) / 100;
    canvas_draw_box(canvas, 0, 58, bar_width, 6);
    
    canvas_set_font(canvas, FontSecondary);
    canvas_set_color(canvas, ColorWhite);
    canvas_draw_box(canvas, 48, 57, 32, 7); 
    
    canvas_set_color(canvas, ColorBlack);
    
    // LIGHTWEIGHT MANUAL STRING CONVERSION (Saves ~2KB of active RAM heap)
    char progress_str[8];
    uint8_t val = state->progress;
    if(val == 100) {
        progress_str[0] = '1';
        progress_str[1] = '0';
        progress_str[2] = '0';
        progress_str[3] = '%';
        progress_str[4] = '\0';
    } else if(val >= 10) {
        progress_str[0] = '0' + (val / 10);
        progress_str[1] = '0' + (val % 10);
        progress_str[2] = '%';
        progress_str[3] = '\0';
    } else {
        progress_str[0] = '0' + val;
        progress_str[1] = '%';
        progress_str[2] = '\0';
    }
    
    canvas_draw_str_aligned(canvas, 64, 63, AlignCenter, AlignBottom, progress_str);
}

static void input_callback(InputEvent* input_event, void* ctx) {
    furi_message_queue_put((FuriMessageQueue*)ctx, input_event, 0);
}

